#!/usr/bin/env python3
"""Embed the FENIX autonomous-mode doctrine into the skills that carry FENIX edits.

An installed plugin only receives its own subdirectory, so a skill cannot depend on a file at this
repo's root (FENIX-AUTONOMOUS.md, scripts/trail.sh). Each edited skill therefore carries its own
copy of the short block below, generated here so there is one source and no hand-maintained copies.

  embed_doctrine.py            dry run: report what would change
  embed_doctrine.py --write    insert or refresh the block in every FENIX-edited skill
  embed_doctrine.py --check    exit 1 if a block is missing, stale, or a skill depends on a repo-root file

A file counts as FENIX-edited when it carries the start marker below.
"""
import re
import sys
from pathlib import Path

START = "<!-- fenix:doctrine:start (generated by scripts/embed_doctrine.py; edit the script, not this block) -->"
END = "<!-- fenix:doctrine:end -->"

BLOCK = f"""{START}
> **FENIX autonomous mode, in brief.** Active when the repo's `.compound-engineering/config.yaml` has a line `autonomous: on`, or `FENIX_AUTONOMOUS=1` is set, or the run was launched by `/lfg`. Check with:
> `grep -qs '^autonomous: on' "$(git rev-parse --show-toplevel)/.compound-engineering/config.yaml" || [ "${{FENIX_AUTONOMOUS:-}}" = 1 ]`
>
> Off means this skill behaves exactly as upstream wrote it. On means four rules:
> 1. **Never block.** Where this skill would ask the user, pick its documented default, log the choice, and continue.
> 2. **Prefer the reversible branch.** Narrower scope over wider, a new file over an edit, additive over destructive, deferred over speculative.
> 3. **Proof, or it did not happen.** A unit is done only with an artifact from the running app. "It compiles" or "tests pass" is not proof. If verification cannot run, stop that unit and record why.
> 4. **Irreversible actions still stop:** force-push, history rewrite, merging a PR, data deletion or destructive migrations, printing or rotating secrets, deploys and publishing, spending money. Commit what is proven, write the trail, and report what waits on a human.
>
> **Decision trail.** For each non-obvious decision append one tab-separated row to `docs/autonomous/<YYYY-MM-DD>-<branch>-trail.tsv`, writing the header row first if the file is new. Columns: `timestamp`, `skill`, `decision`, `why`, `evidence` (a path, or `none`), `reversible` (`yes` or `no`). Every `reversible=no` row also goes in the PR description. A run ends with an open PR, never a merge.
{END}"""

# One-time wording migration for the per-skill paragraphs: they used to point at two repo-root files
# that do not ship inside an installed plugin. Idempotent, since the old phrasing disappears.
MIGRATIONS = [
    (r"log one row via `scripts/trail\.sh write`", "log one trail row (format in the box above)"),
    (r"via `scripts/trail\.sh write`", "as a trail row (format in the box above)"),
    (r"`scripts/trail\.sh write`", "a trail row (format in the box above)"),
    (r"run `scripts/trail\.sh check`", "run the FENIX activation check (box above)"),
    (r"`scripts/trail\.sh check` reports", "the FENIX activation check reports"),
    (r"Add `scripts/trail\.sh check` reporting on", "Add the FENIX activation check reporting on"),
    (r"Do not also write to `scripts/trail\.sh` when", "Do not also write a separate FENIX trail row when"),
    (r'\(FENIX-AUTONOMOUS\.md section 4: "an open PR\.\.\. No merge\. Ever\."\)', "(the FENIX end-of-run rule: an open PR, never a merge)"),
    (r"per FENIX-AUTONOMOUS\.md section 4", "per the FENIX end-of-run rule"),
    (r"Per FENIX-AUTONOMOUS\.md section 3,", "Per the FENIX decision trail,"),
    (r"\(doctrine section 3\)", "(the FENIX decision trail)"),
    (r"satisfies FENIX-AUTONOMOUS\.md section 3", "satisfies the FENIX decision-trail requirement"),
    (r"FENIX-AUTONOMOUS\.md's doctrine", "the FENIX doctrine"),
    (r"doctrine section 5 says", "the FENIX doctrine's honest-limits note says"),
    (r"doctrine section 5", "the FENIX doctrine's honest-limits note"),
    (r"FENIX_SHIP_LOOP\.md's own", "the FENIX ship loop's own"),
    (r"FENIX_SHIP_LOOP\.md", "the FENIX ship loop"),
    (r"FENIX-AUTONOMOUS\.md Rules", "FENIX Rules"),
    (r"FENIX-AUTONOMOUS\.md Rule", "FENIX Rule"),
]
FORBIDDEN = ("scripts/trail.sh", "FENIX-AUTONOMOUS.md")
OTHER_REPO_FILES = ("FENIX_SHIP_LOOP.md",)  # lives in the project repos, never inside this one
LOCK = "scripts/fenix-edited.txt"  # the skills that must carry a block; catches an edit lost in a merge
BLOCK_RE = re.compile(re.escape("<!-- fenix:doctrine:start") + r".*?" + re.escape(END), re.DOTALL)


def migrate(text):
    for pattern, repl in MIGRATIONS:
        text = re.sub(pattern.replace(" ", r"\s+"), repl, text)
    return text


def insertion_index(lines):
    """Start of the paragraph holding the first FENIX paragraph, or just after an 'Autonomous mode' heading."""
    first = next((i for i, l in enumerate(lines) if "FENIX" in l), None)
    if first is None:
        return None
    j = first
    while j > 0 and lines[j - 1].strip():
        j -= 1
    return j


def embed(text):
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _m: BLOCK, text, count=1)
    lines = text.split("\n")
    at = insertion_index(lines)
    if at is None:
        return text
    lines[at:at] = BLOCK.split("\n") + [""]
    return "\n".join(lines)


def edited_files(root):
    out = []
    for path in sorted((root / "skills").rglob("*.md")):
        if any(p in ("tests", "docs", "site", "node_modules", "fixtures") for p in path.parts):
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        if "fenix:doctrine:start" in text or any(f in text for f in FORBIDDEN):
            out.append(path)
    return out


def write_lock(root):
    paths = [p.relative_to(root).as_posix() for p in edited_files(root) if "fenix:doctrine:start" in p.read_text(encoding="utf-8", errors="ignore")]
    header = (
        "# Skills that must carry the FENIX doctrine block. Regenerated by embed_doctrine.py --write.\n"
        "# A skill listed here that loses its block (e.g. a merge conflict resolved by taking upstream) fails the closure check.\n"
    )
    (root / LOCK).write_text(header + "\n".join(sorted(paths)) + "\n", encoding="utf-8", newline="\n")
    return len(paths)


def check_lock(root):
    lock = root / LOCK
    if not lock.is_file():
        return [("fenix", LOCK, 0, "missing; generate with: embed_doctrine.py --write")]
    findings = []
    for line in lock.read_text(encoding="utf-8").splitlines():
        rel = line.strip()
        if not rel or rel.startswith("#"):
            continue
        f = root / rel
        if not f.is_file():
            findings.append(("fenix", rel, 0, "listed in fenix-edited.txt but missing on disk"))
        elif "fenix:doctrine:start" not in f.read_text(encoding="utf-8", errors="ignore"):
            findings.append(("fenix", rel, 0, "lost its FENIX edit (merge resolved to upstream?). Restore it: git checkout ORIG_HEAD -- " + rel + " or re-apply by hand, then run embed_doctrine.py --write"))
    return findings


def check_embedded(root):
    """(kind, rel, line, what) findings: stale/missing blocks, or any dependency on an unshipped repo-root file."""
    findings = check_lock(root)
    for path in edited_files(root):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8", errors="ignore")
        m = BLOCK_RE.search(text)
        if not m:
            findings.append(("fenix", rel, 0, "FENIX edit has no embedded doctrine block"))
        elif m.group(0) != BLOCK:
            findings.append(("fenix", rel, 0, "embedded doctrine block is stale; run scripts/embed_doctrine.py --write"))
        for n, line in enumerate(text.split("\n"), 1):
            for f in FORBIDDEN + OTHER_REPO_FILES:
                if f in line:
                    findings.append(("fenix", rel, n, f"depends on {f}, which does not ship inside an installed plugin"))
    return findings


def main(argv):
    root = Path(__file__).resolve().parent.parent
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    if "--check" in argv:
        found = check_embedded(root)
        for kind, rel, line, what in found:
            print(f"FAIL {kind:<8} {rel}:{line}  {what}")
        print(("FAIL" if found else "PASS") + f": {len(found)} FENIX embedding problem(s)")
        return 1 if found else 0
    changed = 0
    for path in edited_files(root):
        old = path.read_text(encoding="utf-8")
        new = embed(migrate(old))
        if new != old:
            changed += 1
            print(f"{'wrote' if '--write' in argv else 'would change'}: {path.relative_to(root).as_posix()}")
            if "--write" in argv:
                path.write_text(new, encoding="utf-8", newline="\n")
    if "--write" in argv:
        print(f"{write_lock(root)} skill(s) recorded in {LOCK}")
    print(f"{changed} file(s) {'updated' if '--write' in argv else 'need updating (dry run, pass --write)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
